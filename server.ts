// AI Chatbot endpoint
app.post('/api/chat', async (req, res) => {
  try {
    const { messages, userLanguage } = req.body;

    if (!messages || !Array.isArray(messages)) {
      return res.status(400).json({ error: 'Messages array is required' });
    }

    const langNotice = userLanguage === 'ky'
      ? 'Колдонуучу кыргыз тилин тандаган. Кыргызча абдан так, даана жана сылык жооп бериңиз.'
      : 'Пользователь общается на русском языке. Дайте четкий структурированный ответ с точными фактами и ценами.';

    // Format chat history for Gemini
    const contents = messages.map((m: { role: string; content: string }) => ({
      role: m.role === 'user' ? 'user' : 'model',
      parts: [{ text: m.content }],
    }));

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: contents,
      config: {
        systemInstruction: `${SYSTEM_INSTRUCTION}\n\n${langNotice}`,
        temperature: 0.3,
      },
    });

    const reply = response.text || 'Здравствуйте! Пожалуйста, напишите нам в WhatsApp +996 555 12-34-56 или приходите на ул. Байтик Баатыра 118.';
    res.json({ reply });
  } catch (error: any) {
    console.error('Chat error:', error);
    res.status(500).json({
      error: 'Произошла ошибка при обработке сообщения. Пожалуйста, напишите нам в WhatsApp!',
      details: error?.message,
    });
  }
});

// In production, serve static frontend
if (process.env.NODE_ENV === 'production') {
  app.use(express.static(path.join(__dirname, 'dist')));
  app.get('*', (req, res) => {
    res.sendFile(path.join(__dirname, 'dist', 'index.html'));
  });
}

// Start dev server with Vite middlewares if in development
async function startServer() {
  if (process.env.NODE_ENV !== 'production') {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  }

  app.listen(PORT, HOST, () => {
    console.log(`Server running on http://${HOST}:${PORT}`);
  });
}

startServer();
